"""
FreshCheck AI — Model Evaluation Script  (v2.0)
Member 1 Responsibility: AI/ML Model Development

Evaluates the trained model on the real, held-out test set.
Reports actual accuracy, precision, recall, F1, confusion matrix,
and training curves. NEVER reports simulated or fabricated metrics.

Usage:
    python ml_model/evaluate.py [--model-path PATH] [--data-dir PATH]

Requirements:
    pip install tensorflow>=2.13 scikit-learn matplotlib pillow numpy seaborn

Output files (ml_model/reports/):
    classification_report.txt    <- REAL metrics from actual test set
    confusion_matrix.png
    training_accuracy.png        (requires ml_model/reports/history.json from train.py)
    training_loss.png
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import numpy as np


# ---------------------------------------------------------------------------
# Argument parsing
# ---------------------------------------------------------------------------
def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="FreshCheck AI — Model Evaluation (v2.0)"
    )
    parser.add_argument(
        "--model-path",
        type=str,
        default="ml_model/model/freshness_model.keras",
        help="Path to trained .keras model file.",
    )
    parser.add_argument(
        "--data-dir",
        type=str,
        default="ml_model/dataset/processed",
        help="Root directory containing train/, validation/, test/ subdirectories.",
    )
    parser.add_argument(
        "--reports-dir",
        type=str,
        default="ml_model/reports",
        help="Directory where evaluation reports will be saved.",
    )
    parser.add_argument(
        "--batch-size",
        type=int,
        default=32,
        help="Batch size for evaluation inference.",
    )
    parser.add_argument(
        "--img-size",
        type=int,
        default=224,
        help="Input image size used during training.",
    )
    parser.add_argument(
        "--history-json",
        type=str,
        default="ml_model/reports/history.json",
        help="Path to training history JSON (generated by train.py).",
    )
    return parser.parse_args()


# ---------------------------------------------------------------------------
# Constants — canonical class order (must match train.py)
# ---------------------------------------------------------------------------
CLASS_NAMES = ["Fresh", "Moderate", "Spoiled"]
NUM_CLASSES = 3


# ---------------------------------------------------------------------------
# Load model
# ---------------------------------------------------------------------------
def load_trained_model(model_path: str):
    """Load trained Keras model from disk. Fails clearly if file is missing."""
    if not os.path.isfile(model_path):
        raise FileNotFoundError(
            f"\nTrained model NOT found at: '{model_path}'\n"
            f"You must run training first:\n"
            f"  python ml_model/train.py --data-dir ml_model/dataset/processed\n"
            f"Do NOT evaluate without a real trained model."
        )
    try:
        import keras
        model = keras.models.load_model(model_path, compile=False)
        print(f"[Model] Loaded via keras: {model_path}")
        return model
    except Exception:
        pass
    try:
        import tensorflow as tf
        model = tf.keras.models.load_model(model_path, compile=False)
        print(f"[Model] Loaded via tf.keras: {model_path}")
        return model
    except Exception as e:
        raise RuntimeError(f"Failed to load model from '{model_path}': {e}")


# ---------------------------------------------------------------------------
# Test data generator
# ---------------------------------------------------------------------------
def build_test_generator(data_dir: str, img_size: int, batch_size: int):
    """
    Build test-only generator. Applies normalization only (no augmentation).
    Discovers which classes are actually present in the test directory.

    Returns:
        (generator, list_of_active_class_names)
    """
    try:
        from tensorflow.keras.preprocessing.image import ImageDataGenerator
    except ImportError:
        from keras.preprocessing.image import ImageDataGenerator

    def mobilenet_preprocess(x):
        return (x / 127.5) - 1.0

    test_datagen = ImageDataGenerator(preprocessing_function=mobilenet_preprocess)
    test_dir = os.path.join(data_dir, "test")

    if not os.path.isdir(test_dir):
        raise FileNotFoundError(
            f"Test directory not found: '{test_dir}'\n"
            f"Run: python ml_model/prepare_dataset.py"
        )

    active_classes = [
        cls for cls in CLASS_NAMES
        if os.path.isdir(os.path.join(test_dir, cls))
        and len(os.listdir(os.path.join(test_dir, cls))) > 0
    ]

    if not active_classes:
        raise ValueError(
            f"No class directories with images in '{test_dir}'.\n"
            f"Expected subdirectories: {CLASS_NAMES}"
        )

    if set(active_classes) != set(CLASS_NAMES):
        missing = set(CLASS_NAMES) - set(active_classes)
        print(f"\n[WARNING] Missing classes in test set: {missing}")
        print(f"  Evaluation covers only: {active_classes}")

    test_gen = test_datagen.flow_from_directory(
        test_dir,
        target_size=(img_size, img_size),
        batch_size=batch_size,
        class_mode="categorical",
        classes=active_classes,
        shuffle=False,          # critical: order must match y_true
    )

    print(f"[Evaluation] Test class indices: {test_gen.class_indices}")
    return test_gen, active_classes


# ---------------------------------------------------------------------------
# Confusion matrix plot
# ---------------------------------------------------------------------------
def plot_confusion_matrix(
    cm_array: np.ndarray,
    class_names: list[str],
    reports_dir: str,
) -> None:
    """Plot and save a colour-coded confusion matrix."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(max(6, len(class_names) * 2), max(5, len(class_names) * 2)))

    try:
        import seaborn as sns
        sns.heatmap(
            cm_array,
            annot=True,
            fmt="d",
            cmap="Blues",
            xticklabels=class_names,
            yticklabels=class_names,
            linewidths=0.5,
            ax=ax,
        )
    except ImportError:
        # Fallback without seaborn
        im = ax.imshow(cm_array, interpolation="nearest", cmap=plt.cm.Blues)
        fig.colorbar(im, ax=ax)
        ax.set_xticks(range(len(class_names)))
        ax.set_yticks(range(len(class_names)))
        ax.set_xticklabels(class_names, fontsize=10)
        ax.set_yticklabels(class_names, fontsize=10)
        thresh = cm_array.max() / 2.0
        for i in range(cm_array.shape[0]):
            for j in range(cm_array.shape[1]):
                ax.text(j, i, str(cm_array[i, j]),
                        ha="center", va="center",
                        color="white" if cm_array[i, j] > thresh else "black",
                        fontsize=12, fontweight="bold")

    ax.set_title(
        "FreshCheck AI — Confusion Matrix (Test Set)\n"
        "[ACTUAL results from real test data]",
        fontsize=12, fontweight="bold"
    )
    ax.set_xlabel("Predicted Label", fontsize=11)
    ax.set_ylabel("True Label", fontsize=11)
    plt.tight_layout()
    out_path = os.path.join(reports_dir, "confusion_matrix.png")
    plt.savefig(out_path, dpi=150)
    plt.close(fig)
    print(f"[Reports] Confusion matrix saved: {out_path}")


# ---------------------------------------------------------------------------
# Training curves from history.json
# ---------------------------------------------------------------------------
def plot_history_from_json(history_json: str, reports_dir: str) -> None:
    """Regenerate training accuracy and loss plots from train.py history JSON."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    if not os.path.isfile(history_json):
        print(f"[Reports] History file not found: '{history_json}'")
        print(f"  Training curves not plotted. Run train.py first.")
        return

    with open(history_json, "r") as f:
        history = json.load(f)

    acc = history.get("accuracy", [])
    val_acc = history.get("val_accuracy", [])
    loss = history.get("loss", [])
    val_loss = history.get("val_loss", [])

    if not acc:
        print("[Reports] Empty history JSON — skipping curve plots.")
        return

    epochs = range(1, len(acc) + 1)
    ft_start = len(acc) + 1

    # Append fine-tune history if present
    if "ft_accuracy" in history:
        ft_acc = history["ft_accuracy"]
        ft_val = history["ft_val_accuracy"]
        ft_loss_data = history["ft_loss"]
        ft_val_loss = history["ft_val_loss"]
        ft_start = len(acc) + 1
        all_acc = acc + ft_acc
        all_val = val_acc + ft_val
        all_loss = loss + ft_loss_data
        all_val_loss = val_loss + ft_val_loss
        epochs = range(1, len(all_acc) + 1)
    else:
        ft_start = None
        all_acc, all_val = acc, val_acc
        all_loss, all_val_loss = loss, val_loss

    # Accuracy plot
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(epochs, all_acc, "b-o", markersize=4, label="Training Accuracy")
    ax.plot(epochs, all_val, "r-s", markersize=4, label="Validation Accuracy")
    if ft_start:
        ax.axvline(x=ft_start - 1, color="gray", linestyle="--", linewidth=1,
                   label="Fine-tune start")
    ax.set_title(
        "FreshCheck AI — Training & Validation Accuracy\n"
        "[From actual training run via train.py]",
        fontsize=12, fontweight="bold"
    )
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Accuracy")
    ax.set_ylim(0.0, 1.05)
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(os.path.join(reports_dir, "training_accuracy.png"), dpi=150)
    plt.close(fig)

    # Loss plot
    fig, ax = plt.subplots(figsize=(9, 5))
    ax.plot(epochs, all_loss, "b-o", markersize=4, label="Training Loss")
    ax.plot(epochs, all_val_loss, "r-s", markersize=4, label="Validation Loss")
    if ft_start:
        ax.axvline(x=ft_start - 1, color="gray", linestyle="--", linewidth=1,
                   label="Fine-tune start")
    ax.set_title(
        "FreshCheck AI — Training & Validation Loss\n"
        "[From actual training run via train.py]",
        fontsize=12, fontweight="bold"
    )
    ax.set_xlabel("Epoch")
    ax.set_ylabel("Categorical Cross-Entropy Loss")
    ax.legend()
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(os.path.join(reports_dir, "training_loss.png"), dpi=150)
    plt.close(fig)

    print(f"[Reports] Training curves saved to: {reports_dir}")


# ---------------------------------------------------------------------------
# Main evaluation
# ---------------------------------------------------------------------------
def evaluate(args: argparse.Namespace) -> None:
    """
    Run the full evaluation pipeline.

    All reported metrics are computed on the REAL test set only.
    This function will raise an error if no trained model is found.
    """
    from sklearn.metrics import (
        accuracy_score,
        classification_report,
        confusion_matrix,
        precision_recall_fscore_support,
    )

    os.makedirs(args.reports_dir, exist_ok=True)

    print("=" * 70)
    print("  FreshCheck AI — Model Evaluation  (v2.0)")
    print("  All metrics are from the REAL test set only.")
    print("=" * 70)

    # Load trained model (raises if not found)
    model = load_trained_model(args.model_path)

    # Build test generator — discovers actual classes
    test_gen, active_classes = build_test_generator(
        args.data_dir, args.img_size, args.batch_size
    )
    num_classes = len(active_classes)
    class_labels = list(range(num_classes))

    if test_gen.samples == 0:
        print("ERROR: Test generator has 0 samples. Check the test/ directory.")
        sys.exit(1)

    # Verify model output size matches test classes
    test_batch = next(iter(test_gen))
    test_pred = model(test_batch[0][:1], training=False)
    if hasattr(test_pred, "numpy"):
        test_pred = test_pred.numpy()
    model_outputs = int(test_pred.shape[-1])
    if model_outputs != num_classes:
        print(f"ERROR: Model has {model_outputs} outputs but test set has {num_classes} classes.")
        print("Ensure the model was trained with the same dataset configuration.")
        sys.exit(1)

    # Run inference
    print(f"\n[Evaluation] Running inference on {test_gen.samples} test images...")
    print(f"[Evaluation] Active classes: {active_classes}")
    test_gen.reset()
    y_pred_probs = model.predict(test_gen, verbose=1)
    y_pred = np.argmax(y_pred_probs, axis=1)
    y_true = test_gen.classes  # integer labels in class_indices order

    # Trim y_pred if generator produced extra batches
    y_pred = y_pred[:len(y_true)]

    # === Compute metrics ===
    acc = accuracy_score(y_true, y_pred)

    mac_prec, mac_rec, mac_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=class_labels, average="macro", zero_division=0
    )
    wt_prec, wt_rec, wt_f1, _ = precision_recall_fscore_support(
        y_true, y_pred, labels=class_labels, average="weighted", zero_division=0
    )
    per_prec, per_rec, per_f1, per_support = precision_recall_fscore_support(
        y_true, y_pred, labels=class_labels, average=None, zero_division=0
    )

    report_str = classification_report(
        y_true,
        y_pred,
        labels=class_labels,
        target_names=active_classes,
        digits=4,
        zero_division=0,
    )
    cm_arr = confusion_matrix(y_true, y_pred, labels=class_labels)

    # === Console output ===
    print(f"\n{'='*60}")
    print(f"  TEST SET RESULTS  (actual model — actual test set)")
    print(f"{'='*60}")
    print(f"  Overall Accuracy   : {acc:.4f} ({acc*100:.2f}%)")
    print(f"  Macro Precision    : {mac_prec:.4f}")
    print(f"  Macro Recall       : {mac_rec:.4f}")
    print(f"  Macro F1-Score     : {mac_f1:.4f}")
    print(f"  Weighted Precision : {wt_prec:.4f}")
    print(f"  Weighted Recall    : {wt_rec:.4f}")
    print(f"  Weighted F1        : {wt_f1:.4f}")
    print(f"\n--- Per-Class Metrics ---")
    for i, cls in enumerate(active_classes):
        print(f"  {cls:<12} Prec={per_prec[i]:.4f}  Rec={per_rec[i]:.4f}  "
              f"F1={per_f1[i]:.4f}  Support={per_support[i]}")
    print(f"\n--- Confusion Matrix (rows=True, cols=Predicted) ---")
    header = "          " + "  ".join(f"{c:>12}" for c in active_classes)
    print(header)
    for i, row in enumerate(cm_arr):
        print(f"{active_classes[i]:<10}" + "  ".join(f"{v:>12}" for v in row))
    print(f"{'='*60}\n")

    if num_classes < NUM_CLASSES:
        missing = set(CLASS_NAMES) - set(active_classes)
        print(f"[WARNING] Evaluation covers {num_classes} classes. Missing: {missing}")
        print(f"  This is NOT a complete three-class evaluation.")

    # === Save classification report ===
    report_path = os.path.join(args.reports_dir, "classification_report.txt")
    with open(report_path, "w", encoding="utf-8") as f:
        f.write("FreshCheck AI - Classification Report\n")
        f.write("=" * 70 + "\n")
        f.write("ACTUAL RESULTS - Evaluated on the real held-out test set.\n")
        f.write("These are NOT simulated or fabricated metrics.\n")
        f.write("=" * 70 + "\n")
        f.write(f"Model     : {args.model_path}\n")
        f.write(f"Test Dir  : {args.data_dir}/test\n")
        f.write(f"Img Size  : {args.img_size}x{args.img_size}\n")
        f.write(f"Norm Mode : centered  (pixel/127.5 - 1.0, range [-1, 1])\n")
        f.write(f"Classes   : {active_classes}\n")
        f.write(f"Test Samples: {test_gen.samples}\n")
        f.write("=" * 70 + "\n\n")
        f.write("OVERALL METRICS\n")
        f.write("-" * 40 + "\n")
        f.write(f"Accuracy           : {acc:.4f} ({acc*100:.2f}%)\n")
        f.write(f"Macro Precision    : {mac_prec:.4f}\n")
        f.write(f"Macro Recall       : {mac_rec:.4f}\n")
        f.write(f"Macro F1-Score     : {mac_f1:.4f}\n")
        f.write(f"Weighted Precision : {wt_prec:.4f}\n")
        f.write(f"Weighted Recall    : {wt_rec:.4f}\n")
        f.write(f"Weighted F1        : {wt_f1:.4f}\n\n")
        f.write("PER-CLASS METRICS\n")
        f.write("-" * 40 + "\n")
        f.write(report_str)
        f.write("\n\nCONFUSION MATRIX (rows=True label, cols=Predicted label)\n")
        f.write("-" * 40 + "\n")
        f.write("           " + "  ".join(f"{c:>12}" for c in active_classes) + "\n")
        for i, row in enumerate(cm_arr):
            f.write(f"{active_classes[i]:<11}" + "  ".join(f"{v:>12}" for v in row) + "\n")
        f.write("\n\nMODEL LIMITATIONS\n")
        f.write("-" * 40 + "\n")
        if num_classes < NUM_CLASSES:
            missing = set(CLASS_NAMES) - set(active_classes)
            f.write(f"WARNING: Model trained on {num_classes} classes. Missing: {missing}\n")
            f.write("This is NOT a complete three-class model.\n\n")
        f.write(
            "1. Moderate class data comes from Meat (Half_Fresh label) only.\n"
            "   Moderate for Fruits/Vegetables is not genuinely represented.\n\n"
            "2. Dairy is not supported. No freshness-labelled dairy dataset found.\n\n"
            "3. Generalization to real-world images may be lower than test metrics suggest.\n\n"
            "4. If val_accuracy >> test_accuracy, overfitting may be present.\n"
            "   Increase dropout or collect more diverse training data.\n"
        )
    print(f"[Reports] Classification report saved: {report_path}")

    # === Save confusion matrix plot ===
    try:
        plot_confusion_matrix(cm_arr, active_classes, args.reports_dir)
    except Exception as e:
        print(f"[Reports] Confusion matrix plot failed: {e}")

    # === Plot training curves from history.json ===
    try:
        plot_history_from_json(args.history_json, args.reports_dir)
    except Exception as e:
        print(f"[Reports] Training curve plot failed: {e}")

    print("\n[Evaluation] Complete. All reports saved to:", args.reports_dir)


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def main():
    args = parse_args()
    evaluate(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
